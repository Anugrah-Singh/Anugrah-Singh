# Remove background
ascii_art_no_bg = ascii_art.replace('-', ' ').replace('=', ' ')
lines = ascii_art_no_bg.split('\n')

for filename in ['/home/shubham-singh/code/Anugrah-Singh/light_mode.svg', '/home/shubham-singh/code/Anugrah-Singh/dark_mode.svg']:
    with open(filename, 'r') as f:
        content = f.read()
    
    # We find the existing <text class="ascii"> block
    pattern = re.compile(r'<text x="15" y="30" fill="([^"]+)" class="ascii"[^>]*>.*?</text>', re.DOTALL)
    
    def replacer(match):
        fill_color = match.group(1)
        # Using 5px font size so it's guaranteed to be narrow enough
        # y spacing 5px. Total height: 66 * 5 = 330px.
        # Let's offset it down by 100px so it's vertically centered in 530px
        res = f'<text x="15" y="30" fill="{fill_color}" class="ascii" font-size="5px">\n'
        for i, line in enumerate(lines):
            y = 100 + i * 5
            l = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            res += f'<tspan x="15" y="{y}">{l}</tspan>\n'
        res += '</text>'
        return res

    new_content = pattern.sub(replacer, content)
    with open(filename, 'w') as f:
        f.write(new_content)
    print(f"Fixed overlap in {filename}")
