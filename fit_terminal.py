ascii_art_no_bg = ascii_art.replace('-', ' ').replace('=', ' ')
lines = ascii_art_no_bg.split('\n')

for filename in ['/home/shubham-singh/code/Anugrah-Singh/light_mode.svg', '/home/shubham-singh/code/Anugrah-Singh/dark_mode.svg']:
    with open(filename, 'r') as f:
        content = f.read()

    # 1. Update overall width and height of SVG and rect
    # <svg ... width="985px" height="530px" ...>
    content = re.sub(r'width="985px" height="530px"', 'width="950px" height="450px"', content)
    
    # 2. Update text block x coords from 390 to 350
    content = content.replace('x="390"', 'x="350"')
    
    # 3. Increase ASCII font size to 6px, and line spacing to 6. start y at 24 so it centers nicely.
    pattern = re.compile(r'<text x="15" y="30" fill="([^"]+)" class="ascii"[^>]*>.*?</text>', re.DOTALL)
    def replacer(match):
        fill_color = match.group(1)
        res = f'<text x="15" y="24" fill="{fill_color}" class="ascii" font-size="6px">\n'
        for i, line in enumerate(lines):
            y = 24 + i * 6
            l = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            res += f'<tspan x="15" y="{y}">{l}</tspan>\n'
        res += '</text>'
        return res

    content = pattern.sub(replacer, content)

    # 4. Shorten the decorative lines at the top to match the new width
    content = content.replace('Anugrah-Singh</tspan> -———————————————————————————————————————————-—-', 'Anugrah-Singh</tspan> -————————————————————————————————————————————-—-')
    content = content.replace('- Contact</tspan> -——————————————————————————————————————————————-—-', '- Contact</tspan> -—————————————————————————————————————————————-—-')

    with open(filename, 'w') as f:
        f.write(content)
    print(f"Perfect fit applied to {filename}")
