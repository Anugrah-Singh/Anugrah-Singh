# Remove the background by replacing '-' and '=' with spaces
ascii_art_no_bg = ascii_art.replace('-', ' ').replace('=', ' ')

lines = ascii_art_no_bg.split('\n')

for filename in ['/home/shubham-singh/code/Anugrah-Singh/light_mode.svg', '/home/shubham-singh/code/Anugrah-Singh/dark_mode.svg']:
    with open(filename, 'r') as f:
        content = f.read()
    
    pattern = re.compile(r'<text x="15" y="30" fill="([^"]+)" class="ascii"[^>]*>.*?</text>', re.DOTALL)
    
    def replacer(match):
        fill_color = match.group(1)
        res = f'<text x="15" y="30" fill="{fill_color}" class="ascii" font-size="7px">\n'
        for i, line in enumerate(lines):
            y = 30 + i * 7
            l = line.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
            # Preserve space explicitly in SVG text if needed, but normally xml:space="preserve" on parent or just pre works.
            # The CSS has text, tspan {white-space: pre;}, so spaces are preserved.
            res += f'<tspan x="15" y="{y}">{l}</tspan>\n'
        res += '</text>'
        return res

    new_content = pattern.sub(replacer, content)
    with open(filename, 'w') as f:
        f.write(new_content)
    print(f"Updated {filename}")
